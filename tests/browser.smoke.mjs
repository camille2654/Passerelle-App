import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createApp } from '../src/server.js';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'agenda-browser-'));
const baseURL = 'http://127.0.0.1:8021/agenda';
const { app, browsers } = createApp({ dataDir: dir, baseURL });
const server = app.listen(8021, '127.0.0.1');
await new Promise(r => server.once('listening', r));
let browser;
const errors = [];
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'fr-FR' });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', message => { if (message.type() === 'error' && message.text().includes('Content Security Policy')) errors.push(message.text()); });
  const invite = fs.readFileSync(path.join(dir, 'admin-invitation.txt'), 'utf8').trim();
  await page.goto(invite);
  await page.getByRole('heading', { name: 'Créez votre espace admin' }).waitFor();
  await page.getByLabel('Votre prénom').fill('Camille');
  await page.getByLabel('Identifiant du portail').fill('admin-qa');
  await page.getByLabel('Mot de passe du portail').fill('temporary-qa-password');
  await page.getByRole('button', { name: 'Créer mon espace' }).click();
  await page.getByRole('heading', { name: 'Votre emploi du temps,' }).waitFor();
  await page.getByRole('button', { name: 'Créer un lien d’invitation' }).click();
  await page.locator('#invitation-result:not([hidden])').waitFor();
  const friendInvite = await page.locator('#invitation-url').inputValue();
  assert.ok(friendInvite.includes('#invitation='));
  fs.mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop-admin.png', fullPage: true });
  await page.getByRole('button', { name: 'Se déconnecter' }).click();
  await page.getByRole('heading', { name: 'On se retrouve ici.' }).waitFor();
  await page.goto(friendInvite);
  await page.getByRole('heading', { name: 'Créez votre espace', exact: true }).waitFor();
  await page.getByLabel('Votre prénom').fill('Alex');
  await page.getByLabel('Identifiant du portail').fill('friend-qa');
  await page.getByLabel('Mot de passe du portail').fill('temporary-friend-password');
  await page.getByRole('button', { name: 'Créer mon espace' }).click();
  await page.getByRole('heading', { name: 'Votre emploi du temps,' }).waitFor();
  assert.equal(await page.getByText('Administration · Invitations').count(), 0);
  await page.screenshot({ path: 'test-results/desktop-friend.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/mobile-friend.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByRole('button', { name: 'Connecter mon ENT' }).click();
  await page.getByLabel('Nom ou ville de l’établissement').fill('Lyon');
  await page.getByRole('button', { name: 'Chercher', exact: true }).click();
  await page.getByRole('button', { name: 'Choisir', exact: true }).first().waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: 'Choisir', exact: true }).first().click();
  await page.locator('#ent-frame:not([hidden])').waitFor({ timeout: 60000 });
  await page.getByText('cas.ent.auvergnerhonealpes.fr', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/ent-login.png', fullPage: true });
  const status = await page.evaluate(async () => (await fetch('./api/skolengo/status')).json());
  assert.equal(status.status, 'login');
  assert.equal(status.host, 'cas.ent.auvergnerhonealpes.fr');
  await page.getByRole('button', { name: 'Tab ↹' }).click();
  const loginItem = [...browsers.items.values()][0];
  await loginItem.page.route('https://cas.ent.auvergnerhonealpes.fr/agenda-qa-redirect', route => route.fulfill({ status: 302, headers: { location: 'skoapp-prod://sign-in-callback?code=local-qa-only&state=invalid-state' }, body: '' }));
  await loginItem.page.goto('https://cas.ent.auvergnerhonealpes.fr/agenda-qa-redirect').catch(() => {});
  await new Promise(r => setTimeout(r, 1800));
  assert.equal(loginItem.status, 'error', 'Mismatched OAuth state must be rejected');
  await page.getByRole('button', { name: 'Fermer la connexion' }).click().catch(() => {});
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, desktop: true, mobile: true, invitation: true, icsPortal: true, accountIsolation: true, realEntLoginPage: true, callbackInterception: true, invalidStateRejected: true, screenshots: 'test-results/' }));
} finally {
  await browsers.close();
  await browser?.close();
  await new Promise(r => server.close(r));
  fs.rmSync(dir, { recursive: true, force: true });
}
