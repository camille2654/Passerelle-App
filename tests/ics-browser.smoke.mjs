import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import ICAL from 'ical.js';
import { createApp } from '../src/server.js';
import { dateWindow } from '../src/sync.js';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'agenda-ics-browser-'));
const baseURL = 'http://127.0.0.1:8021/agenda';
const day = dateWindow().start;
const lesson = { id: 'browser-course', startDateTime: day + 'T10:00:00Z', endDateTime: day + 'T11:00:00Z', title: 'Cours de contrôle', location: 'B204', canceled: false, teachers: [] };
const { app, store, browsers } = createApp({ dataDir: dir, baseURL, syncOptions: { clientFactory: async () => ({ getAgenda: async (student, start, end) => day >= start && day <= end ? [{ date: day, lessons: [lesson] }] : [] }) } });
const server = app.listen(8021, '127.0.0.1');
await new Promise(r => server.once('listening', r));
let browser;
const requests = [], errors = [];
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'fr-FR' });
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { const url = new URL(request.url()); if (url.pathname.includes('/api/feed/')) requests.push({ method: request.method(), path: url.pathname }); });
  await page.goto(fs.readFileSync(path.join(dir, 'admin-invitation.txt'), 'utf8').trim());
  await page.getByLabel('Votre prénom').fill('Contrôle');
  await page.getByLabel('Identifiant du portail').fill('ics-check');
  await page.getByLabel('Mot de passe du portail').fill('temporary-test-password');
  await page.getByRole('button', { name: 'Créer mon espace' }).click();
  await page.getByRole('heading', { name: 'Votre emploi du temps,' }).waitFor();
  const user = store.state.users[0];
  store.update(user.id, { skolengo: store.seal({ testFixture: true }), studentId: 'test-student', schoolName: 'Établissement de contrôle', students: [{ id: 'test-student', name: 'Contrôle' }] });
  await page.reload();
  await page.getByRole('button', { name: 'Créer mon lien ICS' }).waitFor();
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/feed/create'));
  await page.getByRole('button', { name: 'Créer mon lien ICS' }).click();
  const response = await responsePromise;
  assert.equal(response.status(), 200, await response.text());
  await page.getByLabel('Lien d’abonnement', { exact: true }).waitFor();
  const url = await page.locator('#feed-url').inputValue();
  const feed = await fetch(url);
  assert.equal(feed.status, 200);
  assert.match(feed.headers.get('content-type'), /^text\/calendar/);
  const calendar = new ICAL.Component(ICAL.parse(await feed.text()));
  assert.ok(calendar.getFirstSubcomponent('vevent').getFirstPropertyValue('summary').endsWith(lesson.title));
  assert.equal(await page.getByRole('link', { name: 'S’abonner à l’agenda' }).getAttribute('href'), url.replace('http:', 'webcal:'));
  fs.mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/ics-created-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'test-results/ics-created-mobile.png', fullPage: true });
  page.on('dialog', dialog => { void dialog.accept(); });
  const rotatePromise = page.waitForResponse(r => r.url().endsWith('/api/feed/rotate'));
  await page.getByRole('button', { name: 'Renouveler le lien' }).click();
  assert.equal((await rotatePromise).status(), 200);
  await page.waitForFunction(old => document.querySelector('#feed-url')?.value !== old, url);
  assert.equal((await fetch(url)).status, 404);
  assert.equal((await fetch(await page.locator('#feed-url').inputValue())).status, 200);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, creation: response.status(), icsDownload: feed.status, parsed: true, mobile: true, rotation: true, requests }));
} finally {
  await browsers.close(); await browser?.close();
  await new Promise(r => server.close(r)); fs.rmSync(dir, { recursive: true, force: true });
}
